# 判官：只判"这批片段够不够回答问题"，不回答问题本身。
#
# 与 `SYSTEM_ANSWER` 第 3 条的区别不是措辞，而是**可核对**：提示词里求模型别猜，效果只能
# 从最终答案里间接体会；判官的输出是两行结构化判断，逐题能核对、误判能归因。
#
# 三条判定口径都是被实测失败逼出来的：
#   - "主题相同"不算够（库外题全部召回了同主题片段，"北京补贴"召回宁波方案）；
#   - "别的地区/别的年份的文件里有"不算够（这是库外题的主要失败形态，所以要把文件名
#     摆进片段块，让判官看得见它讲的是哪儿、哪一年）；
#   - 缺具体事实（数值、名称、单位、办理主体、步骤）就不算够——"讲了这个主题"与
#     "给了这个答案"是两件事。
SYSTEM_JUDGE = """你是资料核对员。你的任务只有一个：判断给定资料片段是否足以回答用户问题。
不要回答问题本身，不要推测片段之外的常识。

判定口径：
1. 片段里必须能直接找到回答所需的**具体事实**——数值、单位、名称、主体、步骤。
   只有主题相同、章节相关、术语相近，都判「不可」。
2. 片段讲的是别的地区、别的年份、别的项目时，若问的正是那个地区/年份/项目，
   判「不可」。片段块首行标明了文件与章节，请据此判断。
3. 片段只给了上位要求（"应符合有关规定""应委托有资质的机构"）而没有具体取值或
   具体对象时，判「不可」。
4. 部分能答、关键项缺失时，判「不可」，并在理由里点出缺的那一项。

输出格式，只输出两行：
第一行：可 或 不可
第二行：不超过 40 字，说明依据或所缺的具体事实
不要输出其他任何内容，不要加标点以外的修饰。"""


def build_judge_prompt(
    question: str, hits: list[Hit], *, top_n: int = 5, per_snippet: int = 400
) -> str:
    """判官输入：与回答用的是同一批片段（前 `top_n` 条），只截短正文控制成本。

    文件名与章节必须在片段块里：库外题的失败形态正是"片段来自别处的文件"，
    把出处抹掉等于让判官失去判据。
    """
    blocks = []
    for n, hit in enumerate(hits[:top_n], start=1):
        path = " > ".join(hit.chapter_path) or hit.title
        text = " ".join((hit.text or "").split())[:per_snippet]
        blocks.append(f"[{n}] 文件：{hit.filename}｜章节：{path}\n{text}")
    context = "\n\n".join(blocks)
    return f"""资料片段：
{context}

用户问题：{question}

请判断以上片段是否足以回答这个问题。"""


def build_judge_retry_prompt(question: str, hits: list[Hit], *, top_n: int = 5,
                             per_snippet: int = 400, system: str | None = None) -> str:
    """上一次输出不是「可/不可」两行时重问一次：只收紧格式，不换判据。

    单独一个函数而不是给原提示加一句话，是为了让"格式重试"在测试里可分辨——
    重试若带上了新的判定口径，两次判断就不是同一把尺子。
    """
    base = build_judge_prompt(question, hits, top_n=top_n, per_snippet=per_snippet)
    return base + "\n\n（上一次输出不符合格式。请只输出两行：第一行「可」或「不可」，第二行理由。）"


# 判官 v2：先分问题类型，再按类型取判据。
#
# v1 只有一条口径——"片段里必须直接找到具体事实"。它在库外题上很有效（34 题拦 33），
# 但把库内口语题也一起拦了（122 题判不可 41，其中 21 题的 gold 就在它看到的 5 条里）。
# 逐题看那 21 条，失败形态高度一致：**问句要的是结论，语料给的是要求**——
#
#   问「吊顶装灯装风机，会不会塌」 → 片段「吊顶系统与设备管线应各自设置吊件，并应满足荷载计算要求」
#   问「厨房台面做多高才不累腰」   → 片段「地柜台面完成面高度宜为 800mm、850mm、900mm」
#   问「装修完怎么判断能不能住」   → 片段是室内环境污染控制的检测项目与限值
#
# 人能一步把"满足荷载计算要求"读成"不会塌"，v1 的判据不认这一步。所以 v2 分开处理：
# 问取值就必须给同类型的取值（这条挡住 near_topic 的大多数），问做法/结论则给出相关
# 措施就算够（这条放过口语题）。对象不同（别的地区/年份/项目/材料）仍然一律判不可。
SYSTEM_JUDGE_V2 = """你是资料核对员。你的任务只有一个：判断给定资料片段是否足以回答用户问题。
不要回答问题本身，不要推测片段之外的常识。

第一步，先判断问题问的是什么（在心里判断，不要输出）：
A. 取值型：问一个可以照录的取值或名称——多少、几天、几个月、多少毫米、多少钱、
   哪个部门、哪个标准编号、什么牌号。
B. 做法/结论型：问会不会、能不能、怎么弄、为什么、该怎么处理、是什么来头。

第二步，按类型判：
A. 取值型——片段必须出现**同一类型**的取值（数值带单位、机构名、标准号、牌号）。
   只写"应符合有关规定""应满足荷载计算要求""应委托有资质的机构"，判「不可」。
   片段给的取值与问题要的不是一回事（问造价给补贴、问天数给月份），也判「不可」。
B. 做法/结论型——片段给出了对应的构造做法、措施、允许或禁止的情形，就判「可」。
   不要求片段里出现问句的那些词，也不要求片段直接写出结论句。
   只有片段讲的是完全不同的对象（别的部位、别的工艺）时才判「不可」。

第三步，无论哪种类型，出现以下情形一律判「不可」：
1. 片段讲的是别的地区、别的年份、别的项目，而问的正是那个地区/年份/项目；
2. 关键项缺失、只答了问题的一半；
3. 片段的句子本身被截断，意思不完整。

输出格式，只输出两行：
第一行：可 或 不可
第二行：不超过 40 字，说明依据或所缺的具体事实
不要输出其他任何内容，不要加标点以外的修饰。"""

# 判官版本表：脚本用 `--judge v1|v2` 切换，dump 里记版本名。
# 两个版本共用同一份冻结候选，所以两行数字是同一批证据上的 A/B。
JUDGE_PROMPTS = {"v1": SYSTEM_JUDGE, "v2": SYSTEM_JUDGE_V2}


def build_answer_prompt(question: str, hits: list[Hit], filters_desc: str) -> str:
    blocks = []
    for n, hit in enumerate(hits, start=1):
        path = " > ".join(hit.chapter_path) or hit.title
        blocks.append(
            f"[{n}] 项目：{hit.project_name}｜文件：{hit.filename}｜章节：{path}\n{hit.text}"
        )
    context = "\n\n".join(blocks)
    scope = f"当前检索范围：{filters_desc}\n\n" if filters_desc else ""
    return f"""{scope}资料片段：
{context}

用户问题：{question}

请基于以上片段作答。"""


def build_summary_prompt(project_name: str, hits: list[Hit]) -> str:
    snippets = "\n".join(f"- {h.text[:400]}" for h in hits[:5])
    return f"项目：{project_name}\n\n文档片段：\n{snippets}"
